"use client";

import { useState, useEffect, useRef } from "react";
import { motion } from "framer-motion";
import { cn } from "@/lib/utils";
import { 
  Brain, 
  FileText, 
  Clock, 
  CheckCircle, 
  AlertTriangle,
  Copy,
  Check,
  RefreshCw,
  Sparkles
} from "lucide-react";

interface InvestigationReportProps {
  txnId: string;
  report?: string;
  isGenerating?: boolean;
  onRegenerate?: () => void;
  className?: string;
}

